#!/usr/bin/env python3
"""parallel-RDP's shader bank, from slangmosh's C++ output to C.

slangmosh writes one C++ header: the SPIR-V of every shader variant, each
variant's resource layout, and a template struct whose constructor picks
the variants by asking a resolver for each shader's defines. This turns
that header into what the core builds:

  parallel-rdp/shaders/slangmosh.h   the two tables, as they came
  parallel-rdp/shader_bank.h         the bank: a program or shader a slot
  parallel-rdp/shader_bank.c         rdp_shader_bank_init, the constructor

  slangmosh_to_c.py slangmosh.hpp          write the three files
  slangmosh_to_c.py --check                shader_bank.[ch] are what
                                           slangmosh.h's selection says
  slangmosh_to_c.py --hpp out.hpp          slangmosh's header again, from
                                           slangmosh.h

tools/rdp_no_storage_8bit_bank.py, which adds the NO_STORAGE_8BIT variants
to slangmosh's header, reads and writes the bank through this.
"""
import argparse, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RDP = os.path.join(ROOT, "mupen64plus-video-paraLLEl", "parallel-rdp", "parallel-rdp")
TABLES = os.path.join(RDP, "shaders", "slangmosh.h")
BANK_H = os.path.join(RDP, "shader_bank.h")
BANK_C = os.path.join(RDP, "shader_bank.c")
BEGIN = "/* ---- slangmosh's selection, as it came: tools/slangmosh_to_c.py reads it ----\n"
END = "---- */\n"

LICENSE = """/* Copyright (c) 2020 Themaister
 *
 * Permission is hereby granted, free of charge, to any person obtaining
 * a copy of this software and associated documentation files (the
 * "Software"), to deal in the Software without restriction, including
 * without limitation the rights to use, copy, modify, merge, publish,
 * distribute, sublicense, and/or sell copies of the Software, and to
 * permit persons to whom the Software is furnished to do so, subject to
 * the following conditions:
 *
 * The above copyright notice and this permission notice shall be
 * included in all copies or substantial portions of the Software.
 *
 * THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND,
 * EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF
 * MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT.
 * IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY
 * CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT,
 * TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE
 * SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.
 */
"""
GENERATED = "/* Generated by tools/slangmosh_to_c.py from slangmosh's output: do not edit. */\n"


def split(text):
    """slangmosh's header: (the tables, the struct's members, the constructor's body)"""
    start = text.index("static const uint32_t spirv_bank[]")
    struct = text.index("template <typename Program, typename Shader>")
    tables = text[start:struct]
    members = re.findall(r"^\t(Program|Shader) (\w+)(\[\d+\])? = \{\};$", text[struct:], re.M)
    ctor = text.index("Shaders(Device &device, Layout &layout, const Resolver &resolver)", struct)
    body_start = text.index("{\n", ctor) + 2
    body_end = text.rindex("\t}\n};")
    return tables, members, text[body_start:body_end]


def selection(body):
    """the constructor's body, in C"""
    out = []
    for line in body.split("\n"):
        if not line.strip():
            continue
        if line.startswith("\t\t"):
            line = line[1:]
        line = line.replace('resolver("', 'resolver(user, "')
        line = re.sub(r"layout\.unserialize\((reflection_bank \+ \d+), (\d+)\);",
                      r"granite_resource_layout_unserialize(&layout, \1, \2);", line)
        line = re.sub(r"this->(\w+(?:\[\d+\])?) = device\.request_program\((spirv_bank \+ \d+), (\d+), &layout\);",
                      r"bank->\1 = compute_program(device, \2, \3, &layout);", line)
        line = re.sub(r"this->(\w+(?:\[\d+\])?) = device\.request_shader\((spirv_bank \+ \d+), (\d+), &layout\);",
                      r"bank->\1 = granite_program_cache_shader(&device->program_cache, \2, \3, &layout);", line)
        if "this->" in line or "device." in line or "layout." in line:
            raise SystemExit("slangmosh_to_c: a line it does not know: " + line.strip())
        out.append(line)
    return "\n".join(out) + "\n"


def bank_h(members):
    slots = "".join("\tgranite_%s_t *%s%s;\n" % ("program" if kind == "Program" else "shader", name, dim)
                    for kind, name, dim in members)
    return (LICENSE + GENERATED + """
#ifndef RDP_SHADER_BANK_H
#define RDP_SHADER_BANK_H

#include <retro_common_api.h>
#include "device.h"

RETRO_BEGIN_DECLS

/* The renderer's and the VI's shaders: compute programs, and the vertex
 * and fragment shaders graphics programs are made of. The device's
 * program cache owns them all. */
typedef struct rdp_shader_bank
{
""" + slots + """} rdp_shader_bank_t;

/* The value (0 or 1) of @define for the shader @name: which of its
 * variants is used */
typedef int (*rdp_shader_define_fn)(void *user, const char *name, const char *define);

/* Makes each slot's shader in the variant @resolver picks. A slot is
 * NULL when its shader could not be made. */
void rdp_shader_bank_init(rdp_shader_bank_t *bank, granite_device_t *device, rdp_shader_define_fn resolver,
\t\tvoid *user);

RETRO_END_DECLS

#endif
""")


def bank_c(body):
    return (LICENSE + GENERATED + """
#include <string.h>
#include "shader_bank.h"
#include "shaders/slangmosh.h"

static granite_program_t *compute_program(granite_device_t *device, const uint32_t *code, size_t size,
\t\tconst granite_resource_layout_t *layout)
{
\treturn granite_program_cache_compute(&device->program_cache,
\t\t\tgranite_program_cache_shader(&device->program_cache, code, size, layout));
}

void rdp_shader_bank_init(rdp_shader_bank_t *bank, granite_device_t *device, rdp_shader_define_fn resolver,
\t\tvoid *user)
{
\tgranite_resource_layout_t layout;

\tmemset(bank, 0, sizeof(*bank));
\tmemset(&layout, 0, sizeof(layout));

""" + selection(body) + "}\n")


def tables_h(tables, members, body):
    kept = "".join("%s %s%s\n" % m for m in members)
    return ("/* Autogenerated from slangmosh (through tools/slangmosh_to_c.py), do not edit. */\n"
            "/* For one C file: shader_bank.c. */\n"
            "#ifndef RDP_SLANGMOSH_H\n#define RDP_SLANGMOSH_H\n#include <stdint.h>\n"
            + tables + BEGIN + kept + "--\n" + body + END + "#endif\n")


def read_kept(text):
    kept = text[text.index(BEGIN) + len(BEGIN):text.rindex(END)]
    slots, body = kept.split("--\n", 1)
    members = [re.match(r"(Program|Shader) (\w+)(\[\d+\])?$", l).groups("") for l in slots.strip().split("\n")]
    return members, body


def to_hpp(text):
    """slangmosh's header, as it was before split() and tables_h()"""
    members, body = read_kept(text)
    tables = text[text.index("static const uint32_t spirv_bank[]"):text.index(BEGIN)]
    return ("// Autogenerated from slangmosh, do not edit.\n#pragma once\n#include <stdint.h>\nnamespace RDP\n{\n"
            + tables + "template <typename Program, typename Shader>\nstruct Shaders\n{\n"
            + "".join("\t%s %s%s = {};\n" % m for m in members)
            + "\n\ttemplate <typename Device, typename Layout, typename Resolver>\n"
              "\tShaders(Device &device, Layout &layout, const Resolver &resolver)\n\t{\n"
            + body + "\t}\n};\n}\n")


def read_hpp():
    """slangmosh's header, out of the files the core builds"""
    with open(TABLES) as f:
        return to_hpp(f.read())


def write(hpp):
    """the three files, from slangmosh's header"""
    tables, members, body = split(hpp)
    members = [(k, n, d or "") for k, n, d in members]
    for path, text in ((TABLES, tables_h(tables, members, body)), (BANK_H, bank_h(members)), (BANK_C, bank_c(body))):
        with open(path, "w") as f:
            f.write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("header", nargs="?")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--hpp")
    a = ap.parse_args()
    if a.hpp:
        with open(a.hpp, "w") as f:
            f.write(read_hpp())
        return 0
    if a.check:
        with open(TABLES) as f:
            kept = f.read()
        members, body = read_kept(kept)
        ok = True
        tables, again, body_again = split(to_hpp(kept))
        if tables_h(tables, [(k, n, d or "") for k, n, d in again], body_again) != kept:
            print("slangmosh_to_c: slangmosh.h is not what its own contents give")
            ok = False
        for path, want in ((BANK_H, bank_h(members)), (BANK_C, bank_c(body))):
            with open(path) as f:
                if f.read() != want:
                    print("slangmosh_to_c: %s is not what slangmosh.h's selection gives" % os.path.basename(path))
                    ok = False
        print("slangmosh_to_c: %s" % ("ok" if ok else "FAIL"))
        return 0 if ok else 1
    if not a.header:
        ap.error("the slangmosh header to convert")
    with open(a.header) as f:
        write(f.read())
    return 0


if __name__ == "__main__":
    sys.exit(main())
