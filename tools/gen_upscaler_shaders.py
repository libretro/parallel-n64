#!/usr/bin/env python3
"""The temporal upscaler's shaders for parallel-RDP, compiled to SPIR-V.

parallel-RDP's own shader bank comes from slangmosh; the upscaler's few
shaders are compiled here with glslangValidator into
parallel-rdp/parallel-rdp/upscaler_shaders.hpp, which is committed so a
build needs no shader compiler.

  gen_upscaler_shaders.py            regenerate the header
  gen_upscaler_shaders.py --check    the header is current: every source's
                                     hash matches the one recorded beside
                                     its SPIR-V, and spirv-val (when found)
                                     accepts the SPIR-V
"""
import argparse, hashlib, os, re, shutil, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RDP = os.path.join(ROOT, "mupen64plus-video-paraLLEl", "parallel-rdp", "parallel-rdp")
SHADERS = ["upscaler_color.comp", "upscaler_motion.vert", "upscaler_motion.frag"]
HEADER = os.path.join(RDP, "upscaler_shaders.hpp")


def ident(name):
    return name.replace(".", "_")


def source_hash(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read().replace(b"\r\n", b"\n")).hexdigest()


def compile_spirv(path, out):
    subprocess.check_call(["glslangValidator", "-V", "--target-env", "vulkan1.1",
                           "-o", out, path], stdout=subprocess.DEVNULL)
    with open(out, "rb") as f:
        data = f.read()
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def generate():
    lines = ["/* Generated by tools/gen_upscaler_shaders.py from shaders/upscaler_*: do not edit. */",
             "#pragma once", "#include <stdint.h>", "", "namespace RDP", "{", "namespace UpscalerShaders", "{"]
    with tempfile.TemporaryDirectory() as tmp:
        for name in SHADERS:
            src = os.path.join(RDP, "shaders", name)
            words = compile_spirv(src, os.path.join(tmp, name + ".spv"))
            lines.append("/* %s sha256 %s */" % (name, source_hash(src)))
            lines.append("static const uint32_t %s[] = {" % ident(name))
            for i in range(0, len(words), 8):
                lines.append("\t" + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",")
            lines.append("};")
            lines.append("")
    lines += ["}", "}", ""]
    with open(HEADER, "w", newline="\n") as f:
        f.write("\n".join(lines))


def check():
    with open(HEADER) as f:
        text = f.read()
    ok = True
    for name in SHADERS:
        m = re.search(r"/\* %s sha256 ([0-9a-f]{64}) \*/\s*static const uint32_t %s\[\] = \{(.*?)\};"
                      % (re.escape(name), ident(name)), text, re.S)
        if not m:
            print("%s: not in upscaler_shaders.hpp" % name)
            ok = False
            continue
        if m.group(1) != source_hash(os.path.join(RDP, "shaders", name)):
            print("%s: changed since upscaler_shaders.hpp was generated; run tools/gen_upscaler_shaders.py" % name)
            ok = False
        if shutil.which("spirv-val"):
            words = [int(w, 16) for w in re.findall(r"0x([0-9a-f]{8})u", m.group(2))]
            with tempfile.NamedTemporaryFile(suffix=".spv", delete=False) as f:
                f.write(b"".join(w.to_bytes(4, "little") for w in words))
                spv = f.name
            try:
                if subprocess.call(["spirv-val", "--target-env", "vulkan1.1", spv]) != 0:
                    print("%s: spirv-val rejects its SPIR-V" % name)
                    ok = False
            finally:
                os.unlink(spv)
    print("upscaler shaders: %s" % ("ok" if ok else "FAILED"))
    return 0 if ok else 1


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        sys.exit(check())
    generate()
